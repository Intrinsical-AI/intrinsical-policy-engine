"""Export structural JSON Schemas from the engine's authoritative Pydantic models.

Schemas help editors and schema-aware tooling. Field/model validators, cross-file
references, engine compatibility, filesystem containment and conditional output
collisions still require the pack compiler or the relevant runtime boundary.
"""

from __future__ import annotations

import argparse
import hashlib
import json
from collections.abc import Sequence
from pathlib import Path
from typing import Any

from pydantic import BaseModel

from intrinsical_policy_engine.adapters.export.base.models.export_config import ExportSettings
from intrinsical_policy_engine.common.constants import CANONICAL_ENGINE_VERSION
from intrinsical_policy_engine.domain.bundles.models import BacklogConfig, BundleProfilesContract
from intrinsical_policy_engine.domain.conditions import Condition
from intrinsical_policy_engine.domain.contract_models import (
    ActionsContract,
    ArticlesContract,
    CalendarContract,
    ContractBundle,
    DueRulesContract,
    FlagsContract,
    FrameworkPresentation,
    FrameworkSemantics,
    PackManifest,
    QuestionnaireContract,
    RulesContract,
    RuntimePolicies,
)
from intrinsical_policy_engine.domain.input_models import AssessmentInput

SCHEMA_MODELS: dict[str, type[BaseModel]] = {
    "actions": ActionsContract,
    "articles": ArticlesContract,
    "assessment-input": AssessmentInput,
    "backlog-config": BacklogConfig,
    "bundle-profiles": BundleProfilesContract,
    "calendar": CalendarContract,
    "condition": Condition,
    "contract-bundle": ContractBundle,
    "due-rules": DueRulesContract,
    "export-settings": ExportSettings,
    "flags": FlagsContract,
    "framework-presentation": FrameworkPresentation,
    "framework-semantics": FrameworkSemantics,
    "pack-manifest": PackManifest,
    "questionnaire": QuestionnaireContract,
    "rules": RulesContract,
    "runtime-policies": RuntimePolicies,
}

VALIDATION_LIMITS = (
    "JSON Schema describes model structure and expressible field constraints; "
    "it does not execute Python field or model validators.",
    "Use ipe lint --contracts PATH --strict for complete pack compilation, "
    "including references, paths, engine compatibility and unconditional output collisions.",
    "Use assess_from_bundle for programmatic contract validation "
    "and the assessment input boundary.",
    "Assessment input requires exactly one non-null answers or flags field; "
    "that model-level invariant is not represented by the generated schema.",
    "Condition positivity, valid calendar dates, profile/node relationships and "
    "export URL/header constraints require their authoritative Pydantic validators.",
    "Runtime selection, filesystem containment, evidence quality and integrity "
    "checks are outside structural schema validation.",
)


def json_bytes(value: Any) -> bytes:
    return (json.dumps(value, indent=2, sort_keys=True, ensure_ascii=False) + "\n").encode("utf-8")


def schema_artifacts() -> dict[str, bytes]:
    """Return reproducible schema files and their digest index, without IO."""
    artifacts: dict[str, bytes] = {}
    entries: list[dict[str, str]] = []
    for name, model in sorted(SCHEMA_MODELS.items()):
        filename = f"{name}.schema.json"
        document = model.model_json_schema(mode="validation", by_alias=True)
        document["$schema"] = "https://json-schema.org/draft/2020-12/schema"
        document["$id"] = f"urn:intrinsical-policy-engine:schema:{name}"
        document["$comment"] = (
            "Generated by scripts/export_schemas.py from the authoritative model. "
            "Structural validation only; see index.json validation_limits."
        )
        payload = json_bytes(document)
        artifacts[filename] = payload
        entries.append(
            {
                "file": filename,
                "model": f"{model.__module__}.{model.__qualname__}",
                "sha256": hashlib.sha256(payload).hexdigest(),
            }
        )
    artifacts["index.json"] = json_bytes(
        {
            "schema_index_version": 1,
            "engine_version": CANONICAL_ENGINE_VERSION,
            "pack_format_version": 3,
            "generator": "scripts/export_schemas.py",
            "validation_limits": VALIDATION_LIMITS,
            "schemas": entries,
        }
    )
    return artifacts


def check_artifacts(directory: Path, artifacts: dict[str, bytes]) -> list[str]:
    """Report missing, changed or obsolete generated files without writing."""
    problems: list[str] = []
    for filename, payload in sorted(artifacts.items()):
        path = directory / filename
        if not path.is_file():
            problems.append(f"missing: {filename}")
        elif path.read_bytes() != payload:
            problems.append(f"changed: {filename}")
    for path in sorted(directory.glob("*.schema.json")):
        if path.name not in artifacts:
            problems.append(f"obsolete: {path.name}")
    return problems


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out-dir", type=Path, default=Path("docs/schemas"))
    parser.add_argument("--check", action="store_true", help="Report schema drift without writing")
    arguments = parser.parse_args(argv)
    artifacts = schema_artifacts()
    if arguments.check:
        problems = check_artifacts(arguments.out_dir, artifacts)
        if problems:
            print("Schema drift:\n" + "\n".join(problems))
            return 1
        print(f"Schemas are current: {len(SCHEMA_MODELS)} models")
        return 0
    arguments.out_dir.mkdir(parents=True, exist_ok=True)
    for filename, payload in sorted(artifacts.items()):
        (arguments.out_dir / filename).write_bytes(payload)
    print(f"Wrote {len(SCHEMA_MODELS)} schemas and index to {arguments.out_dir}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
